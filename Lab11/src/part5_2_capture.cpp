// Частина 5. Завдання 2. Захоплення змінних у лямбда-виразах
//
// Результат початкового коду (original/task5_2_original.cpp):
//   6 30
//
// Пояснення:
// - byValue захоплює k за значенням [k]: у момент створення лямбди в неї
//   копіюється значення k = 2, тому byValue(3) = 3 * 2 = 6;
// - byRef захоплює k за посиланням [&k]: лямбда звертається до самої змінної k,
//   тому після k = 10 отримуємо byRef(3) = 3 * 10 = 30.
// Зміна зовнішньої змінної не впливає на копію, але впливає на посилання.
//
// Код компілюється і працює коректно - це не помилка, а різна поведінка
// двох способів захоплення. Нижче показано, як отримати потрібний результат
// в обох випадках.

#include <iostream>

int main() {
    int k = 2;

    auto byValue = [k](int x) {
        return x * k;   // використовує копію k, зроблену при створенні
    };

    auto byRef = [&k](int x) {
        return x * k;   // використовує поточне значення k
    };

    std::cout << "Before k = 10: byValue(3) = " << byValue(3)
              << ", byRef(3) = " << byRef(3) << '\n';

    k = 10;

    std::cout << "After  k = 10: byValue(3) = " << byValue(3)
              << ", byRef(3) = " << byRef(3) << '\n';

    // Якщо потрібно, щоб лямбда за значенням теж використала нове k,
    // її треба створити після зміни змінної:
    auto byValueNew = [k](int x) {
        return x * k;
    };
    std::cout << "byValue created after k = 10: " << byValueNew(3) << '\n';
}
